const TODO_CHECK_MS = 320;
const TODO_HOLD_MS = 6000;       // пауза 5–7 с, по умолчанию 6 с
const TODO_FADE_MS = 1000;       // blur + opacity
const TODO_COLLAPSE_MS = 420;    // схлопывание высоты

